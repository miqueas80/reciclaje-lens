from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1200,'height':900},accept_downloads=True)
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda err: errors.append(str(err)))
    page.goto('http://127.0.0.1:8765/',wait_until='networkidle')
    assert page.locator('#catalogBadge').inner_text().startswith('57'),page.locator('#catalogBadge').inner_text()
    page.locator('#lot').fill('L-2000')
    page.locator('#planId').fill('SOP-IND-01')
    page.locator('#sampleTarget').fill('2')
    page.locator('#operator').fill('Inspector uno')
    page.locator('#sampleId').fill('S-001')
    page.locator('#marking').fill('05 PP')
    assert 'PP' in page.locator('#result').inner_text()
    page.locator('#quantity').fill('2.5')
    page.locator('#unit').select_option('kg')
    page.locator('#saveBtn').click()
    page.wait_for_function("document.querySelector('#kTotal').textContent === '1'")
    page.locator('[data-tab="qa"]').click()
    card=page.locator('.review-card').first
    assert card.is_visible()
    card.locator('.review-operator').fill('Auditor dos')
    card.locator('.review-reason').fill('Revisión material con marca y muestra validada')
    card.locator('.review-check').check()
    page.on('dialog',lambda dlg: dlg.accept())
    card.locator('.review-release').click()
    page.wait_for_function("document.querySelector('#kReleased').textContent === '1'")
    page.locator('[data-tab="scan"]').click()
    page.locator('#marking').fill('>PC+ABS<')
    page.locator('#sampleId').fill('S-002')
    assert 'CUARENTENA' in page.locator('#result').inner_text()
    page.locator('#saveBtn').click()
    page.wait_for_function("document.querySelector('#kTotal').textContent === '2'")
    assert page.locator('#kQuarantine').inner_text()=='1'
    page.locator('[data-tab="lots"]').click()
    assert 'RETENER / REVISAR' in page.locator('#lotsList').inner_text()
    page.locator('[data-tab="history"]').click()
    with page.expect_download() as info:
        page.locator('#csvBtn').click()
    assert info.value.suggested_filename.endswith('.csv')
    # screenshot para control visual
    page.screenshot(path=str(__import__('pathlib').Path(__file__).resolve().parent.parent/'preview-v2.2.png'),full_page=True)
    page.reload(wait_until='networkidle')
    assert page.locator('#kTotal').inner_text()=='2'
    page.wait_for_function('navigator.serviceWorker.controller !== null',timeout=15000)
    context.set_offline(True)
    page.reload(wait_until='domcontentloaded')
    page.wait_for_timeout(400)
    assert page.locator('#kTotal').inner_text()=='2',page.locator('#kTotal').inner_text()
    assert 'Sin Internet' in page.locator('#netLabel').inner_text()
    print('e2e: creación, revisión QA, cuarentena, exportación CSV, recarga y offline: OK')
    print('pageerrors:',errors)
    assert not errors,errors
    browser.close()
